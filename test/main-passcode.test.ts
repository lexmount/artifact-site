import { afterEach, expect, it, vi } from "vitest";
import { closeDbForTests, createId, getSite, rbacQuery, upsertUser } from "@/lib/db";
import { createSite } from "@/lib/sites";
import { mintSession } from "@/lib/session";
import { GET, PUT } from "@/app/api/sites/[slug]/main-sharing/route";
import { POST } from "@/app/api/sites/[slug]/main-sharing/unlock/route";
import { canReadSite, canReadVersion } from "@/lib/share";
import { authorizePreview } from "@/lib/preview-access";
import { resolveCommentAccess } from "@/lib/comments/access";
import { describeCommentPermissions } from "@/lib/comments/permissions";
import { setSharingPreference, scopeChange } from "@/lib/sharing-defaults";
import { admittedMainPasscode, managedMainPasscode } from "@/lib/main-passcode";
import { previewSecret, rotatePreviewSecret } from "@/lib/preview-secret";
const origin = "https://passcode.test";
afterEach(async () => { await closeDbForTests(); vi.unstubAllEnvs(); });
async function fixture() {
  vi.stubEnv("ARTIFACT_MODERATION", "off");
  const owner = await upsertUser({ authProvider: "main-code", providerSubject: createId("owner") });
  const { site } = await createSite({ mode: "paste", html: "<h1>Protected</h1>" }, { ownerId: owner.id });
  const { cookie } = await mintSession(new Request(origin), owner.id);
  const ctx = { params: Promise.resolve({ slug: site.slug }) };
  const request = (method = "GET", body?: unknown, credential = cookie) => new Request(`${origin}/api/sites/${site.slug}/main-sharing`, { method, headers: { origin, cookie: credential, "content-type": "application/json" }, body: body === undefined ? undefined : JSON.stringify(body) });
  const save = (audience: string, extra = {}) => PUT(request("PUT", { action: "custom", policy: { audience, comments: true }, ...extra }), ctx);
  const unlock = (passcode: string) => POST(request("POST", { passcode }, ""), ctx);
  return { owner, site, ctx, request, save, unlock };
}
it("protects the unchanged main address, comments and cookie-free resources; resets revoke old proof", async () => {
  const f = await fixture();
  const response = await f.save("passcode");
  expect(response.status).toBe(200);
  const state = await response.json();
  expect(state.policy.audience).toBe("passcode");
  expect(state.passcode).toMatch(/^[2-9A-HJ-NP-Z]{6}$/);
  const stored = await rbacQuery("SELECT * FROM main_link_passcodes WHERE site_id=$1", [f.site.id]);
  expect(JSON.stringify(stored)).not.toContain(state.passcode);
  expect((await (await GET(f.request(), f.ctx)).json()).passcode).toBe(state.passcode);
  expect((await GET(f.request("GET", undefined, ""), f.ctx)).status).toBe(403);
  const site = (await getSite(f.site.id))!;
  expect(site.visibility).toBe("private");
  expect(await canReadSite(new Request(origin), site)).toBe(false);
  expect(await canReadSite(f.request(), site)).toBe(true);
  expect((await f.unlock("WRONG1")).status).toBe(403);
  const unlocked = await f.unlock(state.passcode.toLowerCase());
  expect(unlocked.status).toBe(200);
  const cookie = unlocked.headers.get("set-cookie")!.split(";")[0];
  const visitor = f.request("GET", undefined, cookie);
  expect(await canReadVersion(visitor, site, site.currentVersionId)).toBe(true);
  const preview = await authorizePreview(visitor, site, null);
  expect(preview?.key).toBeTruthy();
  expect(await authorizePreview(new Request(origin), site, preview!.key)).not.toBeNull();
  const scope = { siteId: site.id, versionId: site.currentVersionId, entry: { kind: "main" as const } };
  await rbacQuery("UPDATE site_comment_settings SET reader_access=1 WHERE site_id=$1", [site.id]);
  expect(describeCommentPermissions(await resolveCommentAccess(visitor, site, scope)).canRead).toBe(true);
  const reset = await PUT(f.request("PUT", { action: "reset-passcode", expectedRevision: state.revision }), f.ctx);
  expect(reset.status).toBe(200);
  const updated = await reset.json();
  expect(updated.passcode).not.toBe(state.passcode);
  expect((await f.unlock(state.passcode)).status).toBe(403);
  expect(await canReadSite(visitor, site)).toBe(false);
  expect(await authorizePreview(new Request(origin), site, preview!.key)).toBeNull();
  expect(describeCommentPermissions(await resolveCommentAccess(visitor, site, scope)).canRead).toBe(false);
  expect((await PUT(f.request("PUT", { action: "reset-passcode", expectedRevision: state.revision }), f.ctx)).status).toBe(409);
  expect((await f.save("anyone")).status).toBe(200);
  expect(await rbacQuery("SELECT * FROM main_link_passcodes WHERE site_id=$1", [site.id])).toEqual([]);
  const again = await (await f.save("passcode")).json();
  expect(again.passcode).not.toBe(updated.passcode);
  expect(await canReadSite(visitor, (await getSite(site.id))!)).toBe(false);
});
it("keeps passcodes out of bulk defaults and inherited scopes", async () => {
  const f = await fixture();
  await expect(setSharingPreference(f.request(), "init", { audience: "passcode", comments: true })).rejects.toThrow();
  await expect(scopeChange(f.request(), null, { enabled: true, policy: { audience: "passcode", comments: true } })).rejects.toThrow();
});
it("rejects unauthorized changes, malformed unlocks and forged or expired cookies", async () => {
  const f = await fixture();
  const state = await (await f.save("passcode")).json();
  expect((await PUT(f.request("PUT", { action: "reset-passcode" }, ""), f.ctx)).status).toBe(403);
  const crossOrigin = new Request(f.request("PUT", { action: "reset-passcode" }), { headers: { ...Object.fromEntries(f.request().headers), origin: "https://other.test" } });
  expect((await PUT(crossOrigin, f.ctx)).status).toBe(401);
  expect((await POST(f.request("POST", null, ""), f.ctx)).status).toBe(400);
  expect((await POST(f.request("POST", { passcode: "A".repeat(4096) }, ""), f.ctx)).status).toBe(413);
  const opaqueUnlock = new Request(f.request("POST", { passcode: state.passcode }, ""), { headers: { origin: "null", "content-type": "application/json" } });
  expect((await POST(opaqueUnlock, f.ctx)).status).toBe(200);
  const unlocked = await f.unlock(state.passcode);
  const cookie = unlocked.headers.get("set-cookie")!.split(";")[0];
  expect(unlocked.headers.get("set-cookie")).toContain("HttpOnly; SameSite=Lax");
  expect(unlocked.headers.get("set-cookie")).toContain("Secure");
  const site = (await getSite(f.site.id))!;
  expect(await admittedMainPasscode(f.request("GET", undefined, cookie), site)).not.toBeNull();
  expect(await admittedMainPasscode(f.request("GET", undefined, `${cookie}; ${cookie}`), site)).toBeNull();
  expect(await admittedMainPasscode(f.request("GET", undefined, `${cookie.slice(0, -1)}!`), site)).toBeNull();
  const clock = vi.spyOn(Date, "now").mockReturnValue(Date.now() + 13 * 60 * 60 * 1000);
  try { expect(await admittedMainPasscode(f.request("GET", undefined, cookie), site)).toBeNull(); }
  finally { clock.mockRestore(); }
  await rbacQuery("UPDATE sites SET taken_down_at=$1 WHERE id=$2", [Date.now(), site.id]);
  expect(await admittedMainPasscode(f.request("GET", undefined, cookie), (await getSite(site.id))!)).toBeNull();
  expect((await f.unlock(state.passcode)).status).toBe(404);
});
it("retains the viewable passcode when preview signing keys rotate", async () => {
  const f = await fixture();
  const state = await (await f.save("passcode")).json();
  await rotatePreviewSecret((await previewSecret()).revision, { kind: "token", userId: null });
  expect(await managedMainPasscode(f.site.id)).toBe(state.passcode);
  expect((await f.unlock(state.passcode)).status).toBe(200);
});
it("only offers organization access when both the acting user and artifact have a real organization", async () => {
  const f = await fixture();
  expect((await (await GET(f.request(), f.ctx)).json()).organization.canSelect).toBe(false);
  await rbacQuery("INSERT INTO tenants(id,name) VALUES('design-team','Design team')");
  await rbacQuery("INSERT INTO tenant_members(tenant_id,user_id) VALUES('design-team',$1)", [f.owner.id]);
  await rbacQuery("UPDATE sites SET tenant_id='design-team' WHERE id=$1", [f.site.id]);
  expect((await (await GET(f.request(), f.ctx)).json()).organization.canSelect).toBe(false);
  await rbacQuery("UPDATE users SET tenant_id='design-team' WHERE id=$1", [f.owner.id]);
  expect((await (await GET(f.request(), f.ctx)).json()).organization).toEqual({ name: "Design team", canSelect: true });
});
