import { readFile, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { zipSync } from "fflate";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { limits } from "@/lib/config";
import { translatorFor } from "@/lib/i18n";
import { chooseUploadRoute, INLINE_UPLOAD_MAX_BYTES } from "@/lib/upload-route";
import { DEFAULT_INLINE_BODY_MAX_BYTES, DEFAULT_UPLOAD_LIMITS, isInlineUploadRejection } from "@/lib/upload-contract";
import { ApiError, ArtifactSiteClient } from "../cli/src/client";
import { inspect, oneShotLimit } from "../cli/src/archive";
import { publishPath } from "../cli/src/publish";

const t = translatorFor("en");
const budget = 1024;
let dir: string;
beforeEach(async () => {
  dir = await mkdtemp(path.join(tmpdir(), "upload-contract-"));
  vi.stubEnv("ARTIFACT_SITE_ONE_SHOT_LIMIT", String(budget));
});
afterEach(async () => { vi.restoreAllMocks(); vi.unstubAllEnvs(); await rm(dir, { recursive: true, force: true }); });

function client() {
  // Anonymous uploads have no local recovery journal. Any unexpected network call fails the test.
  const api = new ArtifactSiteClient({ baseUrl: "http://localhost", fetch: async () => { throw new Error("Unexpected request"); } });
  const result = { slug: "contract", url: "/s/contract", title: "Contract", kind: "single" as const, versionId: "version" };
  vi.spyOn(api, "createFile").mockResolvedValue(result);
  vi.spyOn(api, "createZip").mockResolvedValue(result);
  vi.spyOn(api, "uploadLimits").mockResolvedValue(DEFAULT_UPLOAD_LIMITS);
  vi.spyOn(api, "openUpload").mockResolvedValue({ versionId: "version" });
  vi.spyOn(api, "uploadFile").mockResolvedValue({ relpath: "index.html", bytes: budget });
  vi.spyOn(api, "commitUpload").mockResolvedValue(result);
  return api;
}
async function localFile(name: string, size: number) {
  const file = path.join(dir, name);
  await writeFile(file, Buffer.alloc(size));
  return file;
}

it("keeps the standalone CLI contract generated from the canonical browser/server source", async () => {
  const canonical = await readFile(new URL("../src/lib/upload-contract.ts", import.meta.url), "utf8");
  const generated = await readFile(new URL("../cli/src/upload-contract.ts", import.meta.url), "utf8");
  expect(generated, "Run npm run generate:upload-contract after editing the contract").toBe("// Generated by scripts/sync-upload-contract.mjs. Do not edit directly.\n" + canonical);
});

it("retains distinct browser payload and server body budgets and the legacy CLI override", () => {
  for (const key of ["ARTIFACT_SITE_ONE_SHOT_LIMIT", "ARTIFACT_HUB_ONE_SHOT_LIMIT", "ARTIFACT_INLINE_UPLOAD_MAX_BYTES", "ARTIFACT_MAX_BYTES", "ARTIFACT_MAX_FILE_BYTES", "ARTIFACT_MAX_FILES"]) vi.stubEnv(key, "");
  expect(INLINE_UPLOAD_MAX_BYTES).toBe(20 * 1048576);
  expect(oneShotLimit()).toBe(DEFAULT_INLINE_BODY_MAX_BYTES);
  expect(limits.inlineUploadMaxBytes).toBe(24 * 1048576);
  expect({ maxBytes: limits.maxBytes, maxFileBytes: limits.maxFileBytes, maxFiles: limits.maxFiles }).toEqual(DEFAULT_UPLOAD_LIMITS);
  vi.stubEnv("ARTIFACT_HUB_ONE_SHOT_LIMIT", "100");
  expect(oneShotLimit()).toBe(100);
  vi.stubEnv("ARTIFACT_SITE_ONE_SHOT_LIMIT", "200");
  expect(oneShotLimit()).toBe(200);
  vi.stubEnv("ARTIFACT_INLINE_UPLOAD_MAX_BYTES", "300");
  expect(limits.inlineUploadMaxBytes).toBe(300);
});

describe("browser and CLI route the same single-file capabilities", () => {
  it.each(["page.html", "PAGE.HTML", "report.pdf", "REPORT.PDF"])("%s is inline at the boundary, chunked only above it", async name => {
    for (const size of [budget - 1, budget, budget + 1]) {
      const route = size > budget ? "chunked" : "file";
      expect(chooseUploadRoute([{ path: name, size }], budget, t)).toEqual({ kind: route });
      expect((await publishPath(client(), await localFile(name, size))).route).toBe(route);
    }
  });

  it.each(["slides.ppt", "slides.pptx", "text.doc", "TEXT.DOCX"])("%s remains inline-only with client-specific oversized feedback", async name => {
    expect((await publishPath(client(), await localFile(name, budget))).route).toBe("file");
    expect(chooseUploadRoute([{ path: name, size: budget + 1 }], budget, t)).toEqual({ kind: "file" });
    const api = client();
    await expect(publishPath(api, await localFile(name, budget + 1))).rejects.toThrow("Office documents over the one-shot limit");
    expect(api.openUpload).not.toHaveBeenCalled();
    expect(api.createFile).not.toHaveBeenCalled();
  });

  it("preserves the legacy .htm limitation instead of promising chunked support", async () => {
    expect((await publishPath(client(), await localFile("legacy.htm", budget))).route).toBe("file");
    expect(chooseUploadRoute([{ path: "legacy.htm", size: budget + 1 }], budget, t)).toEqual({ kind: "file" });
    const api = client();
    await expect(publishPath(api, await localFile("legacy.htm", budget + 1))).rejects.toThrow(/HTML entry/);
    expect(api.openUpload).not.toHaveBeenCalled();
  });
});

it("the browser requests ZIP extraction while the CLI extracts; expanded bytes decide the CLI channel", async () => {
  expect(chooseUploadRoute([{ path: "site.zip", size: budget + 1 }], budget, t).kind).toBe("error");
  for (const level of [0, 6] as const) {
    const bytes = zipSync({ "index.html": Buffer.alloc(budget + 1) }, { level });
    if (level === 6) expect(bytes.length).toBeLessThan(budget);
    const file = path.join(dir, `site-${level}.zip`);
    await writeFile(file, bytes);
    const api = client();
    expect((await publishPath(api, file)).route).toBe("chunked");
    expect(api.createZip).not.toHaveBeenCalled();
    expect(api.uploadFile).toHaveBeenCalledOnce();
  }
});

it.each([
  [413, { code: "inline_upload_too_large", effect: "none" }, true],
  [413, { code: "inline_upload_too_large" }, false],
  [413, { code: "inline_upload_too_large", effect: "unknown" }, false],
  [413, { code: "other", effect: "none" }, false],
  [413, "proxy error", false],
  [413, null, false],
  [503, { code: "inline_upload_too_large", effect: "none" }, false],
] as const)("fallback is allowed only for confirmed no-effect rejection (%s, %j)", async (status, body, retry) => {
  expect(isInlineUploadRejection(status, body)).toBe(retry);
  const api = client();
  const failure = new ApiError(status, "Rejected", body);
  vi.mocked(api.createFile).mockRejectedValue(failure);
  const promise = publishPath(api, await localFile("index.html", budget));
  if (retry) {
    expect((await promise).route).toBe("chunked");
    expect(api.openUpload).toHaveBeenCalledOnce();
  } else {
    await expect(promise).rejects.toBe(failure);
    expect(api.openUpload).not.toHaveBeenCalled();
  }
});

it("keeps extensionless and dot-only local filenames unsupported", async () => {
  for (const name of ["README", ".html", ".pdf", "photo.png"]) {
    await expect(inspect(await localFile(name, 1))).rejects.toThrow(/Unsupported file type/);
  }
});
